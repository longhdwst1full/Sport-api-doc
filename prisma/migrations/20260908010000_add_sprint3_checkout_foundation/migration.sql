  CONSTRAINT inventory_reservation_items_product_variant_id_fkey FOREIGN KEY (product_variant_id) REFERENCES public.product_variants(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT inventory_reservation_items_reservation_id_product_variant_id_key UNIQUE (reservation_id, product_variant_id)
);
CREATE INDEX inventory_reservation_items_product_variant_id_idx ON public.inventory_reservation_items(product_variant_id);

